  var base = { es: {}, en: EN };
  var lang = "es";
  var orig = new WeakMap();      // nodo -> texto original
  var origAttr = new WeakMap();  // elemento -> {atributo: valor original}
  var ATTRS = ["alt", "aria-label", "placeholder"];
  var oyentes = [];

  function norm(t) { return String(t).replace(/\s+/g, " ").trim(); }
